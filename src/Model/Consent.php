<?php

declare(strict_types=1);

namespace Sklad\Model;

use Sklad\Core\Settings;
use Sklad\Core\View;

/**
 * Согласие на обработку персональных данных — текст галочки.
 *
 * Одно место на всю сеть, потому что текст юридически значим. При отправке
 * заявки сервер кладёт в журнал согласий значение настройки
 * `consent_wording` (RequestController) — именно им потом и доказывают,
 * под чем человек поставил галочку. Значит, на экране обязано стоять ровно
 * оно же.
 *
 * До этого текст собирали в пяти местах и получали четыре разных:
 *
 *   - окна заявок и форма запчастей (public/assets/js/request.js) —
 *     формулировка из настройки, название политики внутри неё сделано
 *     ссылкой;
 *   - корзина базовой темы — формулировка вообще не читалась, в шаблоне
 *     стояла своя фраза, и человек в корзине соглашался с одним текстом,
 *     а в журнал уходил другой;
 *   - главная базовой темы — формулировка плюс ссылка «Политики
 *     конфиденциальности» следом;
 *   - корзина и главная темы tor — формулировка плюс ссылка «Политика
 *     конфиденциальности» следом.
 *
 * Приписанная следом ссылка — не мелочь: настройка у Hangcha и в исходном
 * наполнении кончается словами «на условиях Политики конфиденциальности»,
 * и название печаталось дважды — «…на условиях Политики конфиденциальности
 * Политика конфиденциальности».
 *
 * Поэтому название политики внутри формулировки делаем ссылкой, а не
 * дописываем ссылку следом. Не нашли названия (владелец переписал
 * формулировку по-своему, как у Партнёра и Tisel — там она кончается на «на
 * условиях») — ставим ссылку отдельно: без неё человеку негде прочитать,
 * на что он соглашается.
 *
 * Близнец этого кода — consentHtml() в public/assets/js/request.js: окна
 * заявок рисует браузер, и сервер туда не дотянется. Правится парой:
 * разойдутся — в корзине и в модальном окне снова будут разные тексты.
 */
final class Consent
{
    /** Название политики, если владелец не назвал её сам в формулировке. */
    private const FALLBACK_NAME = 'Политика конфиденциальности';

    /** Куда ведёт ссылка, если адрес не задан. */
    private const FALLBACK_URL = '/politika-konfidencialnosti/';

    /**
     * Готовая разметка текста галочки: формулировка с ссылкой на политику.
     *
     * Возвращает HTML — вставлять без экранирования. Всё, что пришло из
     * настроек, экранировано внутри.
     */
    public static function html(Settings $settings): string
    {
        $wording = trim($settings->get('consent_wording'));

        // Настройка может быть заведена пустой строкой — тогда второй
        // аргумент get() не сработает, он только для отсутствующего ключа.
        $url = trim($settings->get('policy_url'));
        if ($url === '') {
            $url = self::FALLBACK_URL;
        }

        $open = '<a href="' . View::e($url) . '" target="_blank" rel="noopener">';

        // Ищем последнее вхождение: формулировка может упоминать политику
        // дважды, и ссылкой должно стать её название, а не первое слово.
        $at = mb_strrpos($wording, 'Политик');
        if ($at === false) {
            return ($wording === '' ? '' : View::e($wording) . ' ')
                . $open . self::FALLBACK_NAME . '</a>';
        }

        return View::e(mb_substr($wording, 0, $at))
            . $open . View::e(mb_substr($wording, $at)) . '</a>';
    }
}
