    /**
     * Город по адресу площадки.
     *
     * Берём первую часть имени и сверяем со списком. Совпало — это
     * региональный поддомен; не совпало — обычный сайт, города нет.
     * Так «equipment.staging.local» остаётся без города, а
     * «kazan.equipment.staging.local» и «kazan.equipment.example.ru» дают Казань.
     *
     * @return array{slug:string, name:string, in:string, of:string}|null
     */
    public static function fromHost(?string $host): ?array
    {
        $host = mb_strtolower(trim((string) $host));
        if ($host === '') {
            return null;
        }

        // Порт и «www» к делу не относятся.
        $host = (string) preg_replace('/:\d+$/', '', $host);
        $host = (string) preg_replace('/^www\./', '', $host);

        $first = explode('.', $host)[0] ?? '';

        return self::bySlug($first);
    }

    /** @return array{slug:string, name:string, in:string, of:string, address:string, phone:string}|null */
    public static function bySlug(string $slug): ?array
    {
        $slug = mb_strtolower(trim($slug));
        if (!isset(self::LIST[$slug])) {
            return null;
        }

        [$name, $in, $of] = self::LIST[$slug];
        $place = self::PLACES[$slug] ?? [];

        return [
            'slug' => $slug,
            'name' => $name,
            'in' => $in,
            'of' => $of,
            // Пусто — значит своего пункта в городе нет: страница покажет
            // основной адрес, а не приглашение приехать в никуда.
            'address' => (string) ($place['address'] ?? ''),
            'phone' => (string) ($place['phone'] ?? ''),
        ];
    }

    /**
     * Город по названию — так его отдаёт служба определения по адресу.
     *
     * Сверяем по буквам без регистра, дефисов и «ё»: служба пишет
     * «Ростов-на-Дону» и «Орел», а у нас «Ростов-на-Дону» и «Орёл».
     *
     * @return array{slug:string, name:string, in:string, of:string, address:string, phone:string}|null
     */
    /**
     * Подстановка города в готовую страницу.
     *
     * Тексты пишет человек, и город в них должен вставать сам: заказчик
     * писал их именно так — «доставка в {городе}», «склад в {городе}».
     * Иначе на семьдесят пять городов пришлось бы семьдесят пять копий
     * каждой страницы, и правка одной опечатки стоила бы дня работы.
     *
     * Три формы, потому что по-русски одной не обойтись: «Тула» в
     * заголовке, «в Туле» в тексте, «из Тулы» в доставке. Их держит
     * список городов, каждый со своими — угадывать окончания правилами
     * нельзя, на «Нижний Новгород» и «Ростов-на-Дону» любое правило врёт.
     *
     * На основном домене города нет — подставляем Москву: там сидит
     * головной офис, и так же сделано на сайте, с которого мы это брали.
     *
     * @param array|null $city город поддомена; null — основной домен
     */
    public static function fill(string $text, ?array $city): string
    {
        if (!str_contains($text, '{')) {
            return $text;
        }

        $city ??= self::bySlug('moskva');
        if ($city === null) {
            return $text;
        }

        return strtr($text, [
            '{город}' => $city['name'],
            '{городе}' => $city['in'],
            '{города}' => $city['of'],
        ]);
    }

    public static function byName(?string $name): ?array
    {
        $key = self::fold($name);
        if ($key === '') {
            return null;
        }

        foreach (array_keys(self::LIST) as $slug) {
            if (self::fold(self::LIST[$slug][0]) === $key) {
                return self::bySlug((string) $slug);
            }
        }

        return null;
    }

    /** Приводим название к сравнимому виду: без регистра, «ё» и знаков. */
    private static function fold(?string $s): string
    {
        $s = mb_strtolower(trim((string) $s));
        $s = str_replace('ё', 'е', $s);

        return (string) preg_replace('/[^а-яa-z0-9]/u', '', $s);
    }

    /**
     * Город в видимый заголовок страницы.
     *
     * Заголовок вкладки и описание город получают в Site\Page — там же,
     * где решается вопрос длины. Видимому заголовку длина не важна, а вот
     * правило «уже названный город второй раз не приписываем» общее:
     * раздел могли назвать руками «Штабелёры в Туле», и без проверки
     * вышло бы «Штабелёры в Туле в Туле».
     *
     * На основном адресе города нет — заголовок остаётся как написан.
     * Приписывать «в Москве» там нельзя: основной адрес не городской, и
     * заголовок сузился бы до одного города вместо всей страны.
     */
    public static function heading(string $text, ?array $city): string
    {
        $text = trim($text);

        if ($city === null || $text === '' || str_contains($text, $city['in'])) {
            return $text;
        }

        return $text . ' в ' . $city['in'];
    }

    /**
     * Все города — для карты сайта и списка на странице контактов.
     *
     * @return array<int, array{slug:string, name:string, in:string, of:string}>
     */
    public static function all(): array
    {
        $out = [];
        foreach (array_keys(self::LIST) as $slug) {
            $out[] = self::bySlug((string) $slug);
        }

        // По алфавиту: список читают глазами, а не машиной.
        usort($out, static fn (array $a, array $b): int => strcoll($a['name'], $b['name']));

        return $out;
    }
