<?php

declare(strict_types=1);

namespace Sklad\Core;

/**
 * Вход в админку и права.
 *
 * Роли жёсткие, без конструктора прав: их три, они понятны на словах,
 * и гибкая система разрешений здесь была бы механизмом, которым никто
 * не пользуется.
 *
 * Существенное: контент-менеджер не видит заявок. Там персональные
 * данные, и доступ к ним должен быть у тех, кому они нужны по работе, —
 * это не паранойя, а ст. 18.1 152-ФЗ.
 */
final class Auth
{
    /**
     * Что кому доступно. Ключ — раздел админки, значение — роли.
     * admin не перечисляем: ему доступно всё.
     */
    private const RIGHTS = [
        // Менеджер тоже видит каталог: без этого он не видел товаров
        // вовсе — и не мог посмотреть, что именно заказали. Ограничение
        // по ценам разделом не решается: раздел даёт доступ целиком, а
        // закрыть надо одни цены. Оно ниже, в canPrice().
        'catalog' => ['content', 'manager'],
        'content' => ['content'],   // страницы, блоки текста
        'requests' => ['manager'],  // заявки и выгрузка
        'settings' => [],           // настройки сайта — только админ
        'users' => [],              // люди и права — только админ
        'redirects' => ['content'],
        'audit' => [],              // журнал изменений — только админ
    ];

    private ?array $user = null;

    public function __construct(private Db $db)
    {
        // Сессию заводим только тому, у кого она уже есть.
        //
        // Раньше она начиналась на каждый запрос, и это стоило дорого.
        // Во-первых, PHP вместе с сессией штампует «Cache-Control:
        // no-store», то есть ни одну страницу каталога нельзя было
        // положить в кэш — ни браузеру, ни промежуточному серверу.
        // Во-вторых, каждый заход поискового робота создавал на диске
        // файл сессии, а роботов на каталог из тысячи страниц и семи
        // десятков городских поддоменов приходит много: на соседнем
        // сайте сети такие файлы забили диск до отказа, и сайт слёг.
        //
        // Витрина сессию не трогает вовсе — она нужна только админке.
        // Поэтому: печенька есть — поднимаем и читаем, печеньки нет —
        // не начинаем. Тем, кому сессия нужна на запись (вход, ключ
        // формы, сообщение после сохранения), её заводит start().
        if (isset($_COOKIE[session_name()])) {
            $this->start();
        }

        if (!empty($_SESSION['user_id'])) {
            $this->user = $this->db->one(
                'SELECT * FROM user WHERE id = ? AND is_active = 1',
                [$_SESSION['user_id']]
            );
            // Учётку могли отключить, пока человек сидел в админке.
            if ($this->user === null) {
                $this->logout();
            }
        }
    }

    /**
     * Поднять сессию, если она ещё не поднята.
     *
     * За обратным прокси — а так работает почти любой хостинг с
     * балансировщиком — переменная HTTPS до PHP не доходит, и печенька
     * сессии уезжала бы без пометки «только по защищённому соединению».
     * Один запрос по http, и чужой получает сессию администратора.
     */
    public function start(): void
    {
        if (session_status() === PHP_SESSION_ACTIVE) {
            return;
        }

        $secure = !empty($_SERVER['HTTPS'])
            || ($_SERVER['HTTP_X_FORWARDED_PROTO'] ?? '') === 'https'
            || ($_SERVER['SERVER_PORT'] ?? '') === '443';

        session_start([
            'cookie_httponly' => true,
            'cookie_samesite' => 'Lax',
            'cookie_secure' => $secure,
        ]);
    }

    /** Сколько неудачных попыток с одного адреса терпим за четверть часа. */
    private const ATTEMPTS = 10;

    /**
     * И сколько всего по админке за то же время.
     *
     * Порог выше личного, но конечный: перебор с сотни адресов личный
     * счётчик не ловит вовсе. Живой админке столько промахов подряд не
     * нужно — их там от силы двое-трое.
     */
    private const ATTEMPTS_TOTAL = 40;

    /** На сколько секунд задерживаем вход, когда общий порог перебран. */
    private const DELAY_TOTAL = 2;

    /**
     * Перебирать ли пароль дальше.
     *
     * Адрес админки известен и меняется редко, так что без счётчика
     * пароль подбирают спокойно: в журналах хостинга это просто поток
     * запросов, на который никто не смотрит.
     */
    public function throttled(): bool
    {
        // Считаем и по адресу, и по всей админке разом. Первое ловит
        // одиночного перебиральщика, второе — распределённый перебор с
        // разных адресов и случай, когда за одним прокси сидят все.
        $recent = (int) $this->db->value(
            'SELECT COUNT(*) FROM login_attempt WHERE created_at > (NOW() - INTERVAL 15 MINUTE)'
        );

        $mine = (int) $this->db->value(
            'SELECT COUNT(*) FROM login_attempt WHERE ip = ? AND created_at > (NOW() - INTERVAL 15 MINUTE)',
            [$this->ip()]
        );
        if ($mine >= self::ATTEMPTS) {
            return true;
        }

        // Общий порог отвечает задержкой, а не отказом.
        //
        // Отказом он запирал вход всем сразу: постороннему хватало сорока
        // промахов с четырёх адресов, и настоящий администратор с верным
        // паролем получал ?error=slow — пароль даже не проверялся, а снять
        // это из админки нечем, потому что войти в неё и не получается.
        // Из трёх мыслимых путей (не применять порог к своим адресам,
        // считать промахи по учётке, задерживать) выбран третий: он
        // единственный ничего не хочет от схемы и ни у кого не отнимает
        // вход совсем. Перебору две секунды на попытку дороги — вместо
        // сотен попыток в минуту остаются десятки, — а живому человеку
        // стоят одного вздоха, после которого пароль проверяется как
        // обычно.
        //
        // Порядок важен: задержка идёт после личного порога. Иначе адрес,
        // которому и так отказано, держал бы работника PHP занятым по две
        // секунды на каждый свой запрос — то есть сам порог стал бы
        // способом положить сайт.
        if ($recent >= self::ATTEMPTS_TOTAL) {
            sleep(self::DELAY_TOTAL);
        }

        return false;
    }

    public function attempt(string $email, string $password): bool
    {
        $user = $this->db->one('SELECT * FROM user WHERE email = ? AND is_active = 1', [mb_strtolower(trim($email))]);

        // Хеш считаем даже когда учётки нет. Иначе несуществующий адрес
        // отвечает заметно быстрее существующего, и по времени ответа
        // подбирается список живых учёток.
        // Настоящий хеш от заведомо чужого пароля, а не строка похожей
        // длины. Подставная годилась только на вид: password_verify
        // отвергает её сразу, не считая, и несуществующая учётка
        // отвечала заметно быстрее существующей — по этой разнице
        // подбирают список живых.
        static $dummy = null;
        $dummy ??= password_hash(bin2hex(random_bytes(16)), PASSWORD_DEFAULT);
        $hash = $user['password_hash'] ?? $dummy;
        if (!password_verify($password, $hash) || $user === null) {
            $this->db->insert('login_attempt', [
                'ip' => $this->ip(),
                'created_at' => date('Y-m-d H:i:s'),
            ]);

            // Заодно выметаем то, что старше суток. Промахи внутри окна
            // трогать нельзя — на них стоит защита, — но за окном они не
            // нужны никому, а чистки у таблицы нет никакой: раньше её
            // делал удачный вход, и вместе с мусором он уносил защиту.
            // Без этого таблица растёт без предела, а оба счётчика
            // перебирают её целиком на каждый вход.
            $this->db->delete('login_attempt', 'created_at < (NOW() - INTERVAL 1 DAY)');

            return false;
        }

        // Промахи с этого адреса намеренно остаются на месте.
        //
        // Раньше удачный вход стирал их все, и порог не срабатывал никогда:
        // обладателю любой живой учётки — хоть не отключённому уволенному
        // контент-менеджеру — хватало девяти попыток к чужому паролю и
        // десятого входа своей парой, чтобы обнулить и личный счётчик, и
        // общий, а потом начать сначала. Удачный вход говорит только о том,
        // что этот пароль подошёл, а не о том, что девять предыдущих были
        // опиской, — и уж точно не о том, что их не было.

        // Хеш мог быть посчитан старым алгоритмом — пересчитываем молча.
        if (password_needs_rehash($user['password_hash'], PASSWORD_DEFAULT)) {
            $this->db->update('user', ['password_hash' => password_hash($password, PASSWORD_DEFAULT)], 'id = ?', [$user['id']]);
        }

        // Смена идентификатора сессии при входе: иначе чужой заранее
        // подсунутый идентификатор станет идентификатором админа.
        // Сессию сначала поднимаем: у входящего впервые её нет.
        $this->start();
        session_regenerate_id(true);
        $_SESSION['user_id'] = (int) $user['id'];
        $this->user = $user;

        $this->db->update('user', ['last_login_at' => date('Y-m-d H:i:s')], 'id = ?', [$user['id']]);

        return true;
    }

    public function logout(): void
    {
        $this->user = null;
        $_SESSION = [];
        if (session_status() === PHP_SESSION_ACTIVE) {
            session_destroy();
        }
    }

    public function user(): ?array
    {
        return $this->user;
    }

    public function id(): ?int
    {
        return $this->user ? (int) $this->user['id'] : null;
    }

    public function check(): bool
    {
        return $this->user !== null;
    }

    public function can(string $section): bool
    {
        if ($this->user === null) {
            return false;
        }
        if ($this->user['role'] === 'admin') {
            return true;
        }

        return in_array($this->user['role'], self::RIGHTS[$section] ?? [], true);
    }

    /**
     * Может ли этот человек назначать цену.
     *
     * Стоит рядом с can(), но отдельно от него, и это намеренно. Раздел
     * catalog менеджеру открыт нарочно — смотреть, что заказали, — а цена,
     * старая цена и акции (акция это те же две цены, см.
     * Admin\PromoController) ему не подчиняются. Разделом такое не
     * выражается: он пускает в экран целиком.
     *
     * Правило живёт одним местом, а не условиями по контроллерам. Цену
     * записывают из карточки товара и с экрана акций; разложенная россыпью
     * проверка рано или поздно где-нибудь не попадётся, и заметят это по
     * изменившейся на витрине цене, а не по журналу.
     */
    public function canPrice(): bool
    {
        if ($this->user === null) {
            return false;
        }

        // Перечисляем тех, кому можно, а не тех, кому нельзя: если ролей
        // когда-нибудь станет больше, новая по умолчанию цену не тронет.
        return in_array($this->user['role'], ['admin', 'content'], true);
    }

    /**
     * Ключ формы. Без него чужая страница сможет отправить форму от
     * имени вошедшего администратора — например, завести себе учётку.
     */
    public function token(): string
    {
        // Ключ кладётся в сессию, значит она нужна на запись.
        $this->start();

        if (empty($_SESSION['csrf'])) {
            $_SESSION['csrf'] = bin2hex(random_bytes(32));
        }

        return $_SESSION['csrf'];
    }

    public function checkToken(?string $token): bool
    {
        return !empty($_SESSION['csrf']) && is_string($token) && hash_equals($_SESSION['csrf'], $token);
    }

    /** За прокси настоящий адрес приходит заголовком. */
    /**
     * Адрес, по которому считаем попытки входа.
     *
     * Только REMOTE_ADDR. Заголовок X-Forwarded-For присылает сам
     * клиент, и доверять ему здесь нельзя дважды:
     *
     * — меняя его на каждом запросе, пароль подбирают без всякой стены,
     *   потому что счётчик у каждого «нового адреса» пустой;
     * — подставив в него адрес администратора, админку закрывают ему
     *   самому: десять неверных паролей — и настоящий уже не принимается.
     *
     * За обратным прокси REMOTE_ADDR — это адрес прокси, то есть один на
     * всех. Предел тогда общий, и это неудобно, но неудобство здесь
     * лучше дыры: чтобы считать по настоящему адресу, надо знать список
     * доверенных прокси, а его никто не заполнит.
     */
    private function ip(): string
    {
        return mb_substr((string) ($_SERVER['REMOTE_ADDR'] ?? ''), 0, 45);
    }
}
