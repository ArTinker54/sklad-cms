-- ---------------------------------------------------------------------------
-- Свои тексты для городских поддоменов.
--
-- До этого город подставлялся метками: текст писался один раз, а «{городе}»
-- заменялось на «в Туле» или «в Калуге». Для удобства редактора это хорошо,
-- но поисковую задачу не решает: страницы городов отличаются одним словом на
-- двенадцать тысяч знаков, и поисковик считает их копиями. На b2b-store.example.ru
-- так и вышло — 141 поддомен, совпадение текстов 100% после удаления названия
-- города, и ни один в выдачу не попал.
--
-- Здесь хранится ТОЛЬКО то, что для города переписали. Пустое поле означает
-- «взять общее», а не «показать пустоту»: иначе заполнение одного города
-- обнуляло бы остальные, и редактор чинил бы это вручную по всей сети.
--
-- Таблица общая для разделов и страниц: entity говорит, чей это текст.
-- Отдельные таблицы под каждый вид завели бы одинаковый код в двух местах,
-- а полей и правил у них ровно те же.
-- ---------------------------------------------------------------------------

CREATE TABLE IF NOT EXISTS city_content (
    id               INT UNSIGNED NOT NULL AUTO_INCREMENT,
    -- 'category' или 'page'. Без внешнего ключа: он указывал бы в разные
    -- таблицы, а один столбец на два адресата база связать не умеет.
    entity           VARCHAR(16) NOT NULL,
    entity_id        INT UNSIGNED NOT NULL,
    -- Слаг города, как в адресе поддомена: tula, kaluga, spb.
    city             VARCHAR(64) NOT NULL,

    meta_title       VARCHAR(255) NOT NULL DEFAULT '',
    meta_description TEXT NULL,
    intro            TEXT NULL,
    body             MEDIUMTEXT NULL,

    updated_at       DATETIME NOT NULL,
    updated_by       VARCHAR(190) NULL,

    PRIMARY KEY (id),
    -- Одна запись на «раздел + город»: вторая означала бы, что неизвестно,
    -- какой из двух текстов показывать.
    UNIQUE KEY entity_city (entity, entity_id, city),
    -- Витрина спрашивает всегда по этой тройке — по ней и ищем.
    KEY lookup (entity, entity_id, city)
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4;
