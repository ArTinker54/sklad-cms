-- ---------------------------------------------------------------------------
-- Префикс номера заявки: убираем чужой, доставшийся от 007-domain.
--
-- Применённые миграции учитываются по имени файла, без контрольной суммы.
-- Тело 007-domain.sql в копиях сети разошлось: в одной оно заводило
-- request_prefix пустым, в другой — сразу со значением «XL», префиксом
-- Brand. Одинаковым текст файла теперь сделан, но накатанные базы сами
-- уже не сойдутся: имя числится применённым, и исправленный 007 в них
-- не пойдёт никогда. Поэтому починка отдельной миграцией.
--
-- Пустое значение — то самое, ради которого 007 и правился: импорт
-- содержимого заполняет только пустое, и с чужим «XL» сайт сети не мог
-- поставить свой префикс ни из data/<сайт>/content.json, ни при
-- следующей выкладке — заявки уходили покупателю под номером чужого
-- сайта.
--
-- Чистим только значение, оставшееся ровно таким, каким его завела
-- миграция. Свой префикс, поставленный руками в админке или импортом
-- («TOR», «HC»), под условие не подходит и остаётся на месте.
--
-- Brand, где «XL» верен, при этом ничего не теряет: пустое значение
-- подхватывает запасное «XL» в самом коде (Site\RequestController::
-- numberPrefix), и нумерация заявок не меняется. Повторный накат тоже
-- безопасен — совпадать после первого уже нечему.
-- ---------------------------------------------------------------------------
UPDATE setting SET value = '' WHERE `key` = 'request_prefix' AND value = 'XL';

-- ---------------------------------------------------------------------------
-- Подпись и подсказка к настройке — из того же разошедшегося 007.
--
-- Там, где 007 пришёл со значением «XL», подсказка обещает «XL-000123» и
-- молчит о том, что означает пустое поле. После очистки выше человек
-- увидел бы пустую настройку и решил, что префикса нет вовсе. Значение
-- здесь не трогаем: ON DUPLICATE KEY обновляет одни подписи — так же,
-- как в 006-requisites.
-- ---------------------------------------------------------------------------
INSERT INTO setting (`key`, value, title, hint, `group`, type, sort) VALUES
('request_prefix', '', 'Префикс номера заявки',
 'Две-три латинские буквы перед номером: TOR-000123. Пусто — XL',
 'Заявки', 'text', 10)
ON DUPLICATE KEY UPDATE title = VALUES(title), hint = VALUES(hint), `group` = VALUES(`group`);
