-- ---------------------------------------------------------------------------
-- Показывать ли в админке раздел «Заявки».
--
-- Заявка нужна двум разным людям и по-разному. Менеджер работает с ней в
-- почте: письмо приходит таблицей, с фотографией во вложении, отвечает он
-- прямо из него. В админку он при этом не заходит вовсе, и раздел висит
-- там лишней вкладкой (Роман, 01.09).
--
-- Само хранение отключать НЕЛЬЗЯ, и настройка его не отключает. Причин две.
-- Почта на дешёвом хостинге отваливается молча — mail() возвращает успех, а
-- письмо не уходит; если записи не останется, обращение исчезнет вместе с
-- телефоном человека, и узнать о нём будет неоткуда. И согласие на обработку
-- данных (152-ФЗ) ссылается на заявку по номеру: без неё запись о согласии
-- повисает без предмета.
--
-- Значение по умолчанию — «показывать»: настройка накатывается на все базы
-- сети, и молча прятать раздел там, где им пользуются, нельзя. Выключают
-- поштучно, на том сайте, где это мешает.
-- ---------------------------------------------------------------------------

INSERT INTO setting (`key`, value, title, hint, `group`, type, sort) VALUES
('show_requests', '1', 'Показывать раздел «Заявки»',
 'Снимите галку, если заявки читают только в почте. Записываться и уходить на почту они будут по-прежнему — прячется лишь вкладка в админке',
 'Общие', 'flag', 30)
ON DUPLICATE KEY UPDATE title = VALUES(title), hint = VALUES(hint), `group` = VALUES(`group`), type = VALUES(type), sort = VALUES(sort);
