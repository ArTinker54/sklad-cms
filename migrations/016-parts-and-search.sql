-- ---------------------------------------------------------------------------
-- Две настройки, без которых новый сайт сети теряет часть витрины молча.
--
-- `parts_path` движок читал с самого начала: по нему раздел запчастей
-- остаётся в плитках каталога с нулём моделей и открывается формой запроса.
-- А заводили эту настройку руками, прямо в базе Brand и Партнёра, — строки в
-- миграциях не было. У Hangcha её поэтому не оказалось вовсе: раздел
-- запчастей в каталог не попадал, и увидеть, чего не хватает, было негде —
-- в админке настройки тоже нет, если нет строки.
--
-- `search_example` — пример модели в подсказке поиска. Раньше пример был
-- вписан в шаблон, а шаблон один на всю сеть: у Партнёра, Tisel и Hangcha в
-- подсказке стояла модель Brand. Пусто — пример берётся из каталога самого
-- сайта (см. Sklad\Model\SearchHint), и это разумное умолчание; настройка
-- нужна там, где продавец хочет назвать другую модель.
--
-- Значения пустые. Непустое установочное значение перебить из файла данных
-- нельзя — импорт содержимого заполняет только пустое, — и настоящее
-- значение сайта не доехало бы до базы никогда. Образцы в подсказке.
--
-- ON DUPLICATE KEY трогает только подписи: у Brand и Партнёра настройка уже
-- заполнена руками, и перезаписать её значение здесь значит убрать у них
-- раздел запчастей из каталога.
-- ---------------------------------------------------------------------------

INSERT INTO setting (`key`, value, title, hint, `group`, type, sort) VALUES
('parts_path', '', 'Адрес раздела запчастей',
 'Например: /spares/. Этот раздел остаётся в каталоге, даже когда моделей в нём нет, и открывается формой запроса. Пусто — обычный раздел',
 'Каталог', 'text', 35),
('search_example', '', 'Пример модели в строке поиска',
 'Дописывается к подсказке: «Модель, код или тип техники — например CDDK20». Пусто — берётся первая модель каталога',
 'Каталог', 'text', 40)
ON DUPLICATE KEY UPDATE title = VALUES(title), hint = VALUES(hint), `group` = VALUES(`group`), type = VALUES(type), sort = VALUES(sort);
