-- ---------------------------------------------------------------------------
-- Неудачные попытки входа.
--
-- Адрес админки известен: /admin, и меняют его редко. Без счётчика
-- перебрать пароль можно спокойно и незаметно — в журналах хостинга это
-- просто поток запросов, на который никто не смотрит.
--
-- Записываем только неудачные и только адрес со временем. Ни логина, ни
-- тем более пароля здесь нет: в таблице, которая заполняется кем угодно
-- снаружи, им делать нечего.
-- ---------------------------------------------------------------------------
CREATE TABLE login_attempt (
    id              INT UNSIGNED NOT NULL AUTO_INCREMENT,
    ip              VARCHAR(45) NOT NULL,
    created_at      DATETIME NOT NULL,
    PRIMARY KEY (id),
    KEY ip (ip, created_at)
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4;
