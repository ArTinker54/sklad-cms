-- Это не «часто искали» из статистики, а отобранный продавцом список:
-- куда уводить человека с широкого раздела, где выбирать не из чего.
-- Отдельная таблица со связями потребовала бы своего экрана в админке
-- ради дюжины строк, которые всё равно правятся целиком, — поэтому
-- обычное поле, по строке на запрос: «Подпись | /адрес/».
--
-- Пусто у раздела — список берётся от раздела выше по ветке. Иначе один
-- и тот же набор пришлось бы вписывать в каждый подраздел руками, а
-- значит, где-то он остался бы старым.
-- ---------------------------------------------------------------------------
