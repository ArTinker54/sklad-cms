-- ---------------------------------------------------------------------------
-- Цифры первого экрана — настройкой, а не вёрсткой.
--
-- В шаблоне главной они были вписаны намертво: «1985 — год основания завода»,
-- «135 — стран поставок». Это факты про Завод оборудования, завод марки Brand. Тема
-- default общая для всей сети, и на сайте TOR те же цифры оказывались враньём:
-- у другой марки другой завод и другой год.
--
-- Формат — по строке на цифру, значение и подпись через вертикальную черту:
--     1985 | год основания завода
-- Пустая настройка — блок с цифрами не показываем вовсе. Это правильнее, чем
-- показывать чужие: пустое место человек не заметит, а неверный год про
-- «основание завода» подорвёт доверие ко всему остальному на странице.
--
-- Значение по умолчанию пустое: миграция накатывается на все базы сети, и
-- проставить сюда цифры Brand значило бы раздать их и TOR, и Hangcha.
-- У Brand они заполняются отдельно, файлом данных сайта.
-- ---------------------------------------------------------------------------

INSERT INTO setting (`key`, value, title, hint, `group`, type, sort) VALUES
('hero_figures', '', 'Цифры на первом экране',
 'По строке на цифру: значение, вертикальная черта, подпись. Например «1985 | год основания завода». Пусто — блок не показывается',
 'Общие', 'textarea', 29)
ON DUPLICATE KEY UPDATE title = VALUES(title), hint = VALUES(hint), `group` = VALUES(`group`), type = VALUES(type), sort = VALUES(sort);
