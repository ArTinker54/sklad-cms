-- ---------------------------------------------------------------------------
-- Имя сайта для шапки.
--
-- Раньше домен брался из адреса установки. На контуре разработки это
-- railway.app, и посетитель видел в шапке служебный адрес стенда вместо
-- имени сайта. Адрес установки нужен для писем и карты сайта, а в шапке
-- должно стоять то, как сайт называется, — это разные вещи, и совпадают
-- они только на боевом хостинге.
-- ---------------------------------------------------------------------------
INSERT INTO setting (`key`, value, title, hint, `group`, type, sort) VALUES
('site_domain', '', 'Домен в шапке',
 'Показывается рядом со знаком. Пусто — берётся из адреса установки',
 'Общие', 'text', 6)
ON DUPLICATE KEY UPDATE `key` = `key`;

-- ---------------------------------------------------------------------------
-- Марку и приписку к заголовку эта миграция НЕ трогает.
--
-- Здесь стояла очистка значений «Бренд», чтобы новый сайт сети мог задать
-- свои. Но миграции накатываются на все базы сети, включая базу самого
-- Brand, где это значение верное: очистка стирала марку на работающем
-- сайте, а вернуть её было нечем — импорт содержимого заполняет только
-- пустое и только по ключам из файла данных, а brand в файле Brand нет.
--
-- Правильное место для таких значений — data/<сайт>/content.json. Для TOR
-- они там заданы, и импортёр каталога больше не вписывает чужие.
-- ---------------------------------------------------------------------------

-- ---------------------------------------------------------------------------
-- Префикс номера заявки.
--
-- Раньше он выводился из марки, и на работающем сайте нумерация менялась
-- на ходу: заявки шли под «XL-», а из марки получалось «XI-» — номер в
-- переписке с покупателем переставал совпадать с прежними. Значение по
-- умолчанию сохраняет сложившуюся нумерацию.
-- ---------------------------------------------------------------------------
-- Значение пустое: непустое установочное значение нельзя перебить из файла
-- данных сайта — импорт заполняет только пустое. С 'XL' по умолчанию все
-- сайты сети получали бы префикс Brand, и задать свой было бы нечем.
-- Пустое значение подхватывает запасное 'XL' в самом коде, поэтому
-- нумерация на Brand не меняется.
INSERT INTO setting (`key`, value, title, hint, `group`, type, sort) VALUES
('request_prefix', '', 'Префикс номера заявки',
 'Две-три латинские буквы перед номером: TOR-000123. Пусто — XL',
 'Заявки', 'text', 10)
ON DUPLICATE KEY UPDATE `key` = `key`;

