-- ---------------------------------------------------------------------------
-- Разделы и страницы тоже убираются пометкой, а не стиранием.
--
-- Как у товаров, и по той же причине. Стёртая запись уносит с собой
-- адрес: на нём висят ссылки из выдачи, из рекламы и из чужих каталогов,
-- и посетитель попадает на «страница не найдена». Пометка оставляет
-- адрес занятым, так что переадресация работает, а повторно завести
-- раздел с тем же адресом уже не выйдет — что и правильно.
--
-- Плюс возврат: удаление без отката — ловушка. Нажали не туда, и достать
-- запись можно только через базу, то есть через разработчика.
-- ---------------------------------------------------------------------------
ALTER TABLE category ADD COLUMN deleted_at DATETIME NULL AFTER is_published;
ALTER TABLE category ADD KEY deleted_at (deleted_at);

ALTER TABLE page ADD COLUMN deleted_at DATETIME NULL AFTER is_indexable;
ALTER TABLE page ADD KEY deleted_at (deleted_at);
