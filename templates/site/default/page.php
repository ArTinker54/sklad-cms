<?php

use Sklad\Core\View;

/**
 * Текстовая страница: «О компании», «Доставка», «Политика».
 *
 * Содержимое приходит из админки готовой разметкой, поэтому выводится
 * как есть. Правит его тот, кому мы дали доступ, и экранировать здесь
 * нечего — иначе на странице будут видны сами теги.
 *
 * @var array                  $page
 * @var \Sklad\Core\Settings   $settings
 */
$e = [View::class, 'e'];

// Текст, набранный в админке, приходит голыми абзацами — типографику ему
// даёт обёртка. Перенесённая вёрстка свою обёртку уже несёт, и вторая
// удвоила бы отступы.
$body = (string) $page['body'];
$wrap = !str_contains($body, 'class="prose"');

// Кнопка заявки под текстом — с 22.09.2026: дочитав «О компании», «Доставку»
// или «Лизинг», человек оказывается внизу страницы, где кнопка из шапки давно
// прокручена, а своего призыва у текстовой страницы не было ни одного.
//
// Кроме страницы политики: туда приходят прочитать правовой текст, а не
// заказывать технику, и призыв к действию под согласием на обработку данных
// выглядит подлогом.
$policy = trim((string) $settings->get('policy_url', '/politika-konfidencialnosti/'));
$showCta = $policy === '' || (string) ($page['path'] ?? '') !== $policy;
?>
<main id="main" class="container">
  <div class="cathead"><h1><?= $e($page['title']) ?></h1></div>
  <?= $wrap ? '<div class="prose">' : '' ?><?= $body ?><?= $wrap ? '</div>' : '' ?>
  <?php if ($showCta): ?>
    <p class="pagecta"><button class="btn btn--primary" type="button" data-action="request">Оставить заявку</button></p>
  <?php endif; ?>
</main>
