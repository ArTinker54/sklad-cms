<?php
/**
 * Тексты для городов — общий блок карточки раздела и карточки страницы.
 *
 * Вынесен отдельно намеренно: поля, подсказки и пояснения у раздела и
 * страницы одни и те же, а две копии разошлись бы при первой же правке —
 * поправили бы в разделе и забыли в странице.
 *
 * @var array  $row          запись, чей текст правим (раздел или страница)
 * @var array  $cities       все города
 * @var array  $cityContent  уже заполненные города: слаг => поля
 */
use Sklad\Core\View;

// Экранирование объявляем здесь, а не берём из раскладки: у части, вызванной
// через $view->render(), своя область видимости — в неё попадает только общий
// набор и то, что передали явно. Без этой строки $e оказывался пустым, и
// страница падала с «Value of type null is not callable».
$e = [View::class, 'e'];
?>
  <?php // ---------------------------------------------------------------
        // Тексты для городов.
        //
        // Метки вида «{городе}» подставляют название города в общий текст —
        // посетитель видит своё, но для поисковика страницы всех городов
        // остаются копиями и в выдачу попадает одна. Здесь пишут то, что для
        // города правда своё: доставка, сроки, местные предприятия.
        //
        // Пустое поле означает «взять общее». Заполнять все города сразу не
        // нужно и не задумано: начинают с тех, где есть спрос.
        //
        // Блок стоит ВНУТРИ основной формы — так «Сохранить» одно на всё.
        // Отдельной формой городской текст терялся бы у того, кто правил
        // сразу и общий, и городской. ?>
  <div class="pane">
    <h2>Тексты для городов</h2>
    <p class="note">Заполнено:
      <?php $filled = array_keys($cityContent); ?>
      <?= $filled ? '<b>' . $e((string) count($filled)) . '</b> из ' . (int) count($cities)
                  : 'ни одного из ' . (int) count($cities) ?>.
      Серым в поле показано то, что стоит сейчас в общем тексте выше. Оставите
      поле пустым — так и будет, город возьмёт общее. Напишете своё — заменит
      только для этого города, остальные не тронет.</p>
    <p class="note">Заполнять все города не нужно: начните с тех, где есть спрос.
      Чтобы город не склеился с другими в выдаче, текст должен отличаться по сути
      — своя доставка, свои сроки, местные предприятия, — а не одним словом.
      Метки <span class="art">{город}</span>, <span class="art">{городе}</span>,
      <span class="art">{города}</span> работают и здесь.</p>

    <?php // Показываем в пустом поле то, что подставится, если его не трогать.
          // Без этого редактор видел четыре пустых поля и не понимал, что он
          // переопределяет: общий текст лежит выше по странице, и его надо
          // было держать в голове, листая туда-сюда.
          //
          // Разметку из вступления и текста вырезаем и обрезаем по длине:
          // подсказка должна давать узнать текст, а не пересказать его.
          $hint = static function (?string $v, int $max = 110) : string {
              $t = trim(preg_replace('/\s+/u', ' ', strip_tags((string) $v)) ?? '');
              if ($t === '') { return 'пусто и в общем'; }
              return mb_strlen($t) > $max ? mb_substr($t, 0, $max - 1) . '…' : $t;
          }; ?>
    <p class="note">Выберите город:
      <select class="val" id="city-pick" style="width:auto;display:inline-block">
        <option value="">— не выбран —</option>
        <?php foreach ($cities as $c): ?>
          <option value="<?= $e($c['slug']) ?>"><?= $e($c['name']) ?><?=
            isset($cityContent[$c['slug']]) ? ' • заполнен' : '' ?></option>
        <?php endforeach; ?>
      </select></p>

    <?php foreach ($cities as $c): ?>
      <?php $has = $cityContent[$c['slug']] ?? []; ?>
      <div class="city-box" data-city="<?= $e($c['slug']) ?>" hidden>
        <div class="fld"><label class="lbl" for="ct-<?= $e($c['slug']) ?>">Заголовок для поиска</label>
          <input class="val" id="ct-<?= $e($c['slug']) ?>"
                 name="city[<?= $e($c['slug']) ?>][meta_title]"
                 placeholder="<?= $e($hint($row['meta_title'], 90)) ?>"
                 value="<?= $e($has['meta_title'] ?? '') ?>"></div>
        <div class="fld"><label class="lbl" for="cd-<?= $e($c['slug']) ?>">Описание для поиска</label>
          <textarea class="val" id="cd-<?= $e($c['slug']) ?>" rows="2"
                    name="city[<?= $e($c['slug']) ?>][meta_description]"
                    placeholder="<?= $e($hint($row['meta_description'])) ?>"><?= $e($has['meta_description'] ?? '') ?></textarea></div>
        <?php // Вступление есть у раздела, но не у страницы — у неё такого
              // поля нет вовсе. Показывать его там значило бы предлагать
              // заполнить то, что никуда не сохранится. ?>
        <?php if (array_key_exists('intro', $row)): ?>
          <div class="fld"><label class="lbl" for="ci-<?= $e($c['slug']) ?>">Вступление (под заголовком)</label>
            <textarea class="val" id="ci-<?= $e($c['slug']) ?>" rows="3"
                      name="city[<?= $e($c['slug']) ?>][intro]"
                      placeholder="<?= $e($hint($row['intro'])) ?>"><?= $e($has['intro'] ?? '') ?></textarea></div>
        <?php endif; ?>
        <div class="fld"><label class="lbl" for="cb-<?= $e($c['slug']) ?>">Текст внизу страницы</label>
          <textarea class="val" id="cb-<?= $e($c['slug']) ?>" rows="8"
                    name="city[<?= $e($c['slug']) ?>][body]"
                    placeholder="<?= $e($hint($row['body'], 160)) ?>"><?= $e($has['body'] ?? '') ?></textarea>
          <p class="note">Чтобы город не склеивался с другими, текст должен отличаться
             по сути, а не одним словом: своя доставка, свои сроки, местные объекты.
             Очистите все поля — город вернётся к общему тексту.</p></div>
      </div>
    <?php endforeach; ?>
  </div>

