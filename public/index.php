<?php

declare(strict_types=1);

/**
 * Единая точка входа. Всё, кроме статики, приходит сюда.
 *
 * Веб-корень — эта папка, а код и настройки лежат выше неё. На дешёвом
 * хостинге это единственный надёжный способ не отдать наружу config.php
 * с паролем от базы: даже если однажды перестанут работать правила
 * .htaccess, файла в доступной папке просто не будет.
 */

// Заголовки, которые дешевле поставить, чем объяснять их отсутствие.
//
// nosniff — браузер не должен угадывать тип содержимого: загруженный
// файл, который он решит счесть скриптом, выполнится в контексте сайта.
// SAMEORIGIN — админку нельзя показать в рамке на чужой странице и
// заставить админа нажать не туда. Referrer — не выдаём адрес карточки
// заявки чужому сайту при переходе по ссылке из неё.
header('X-Content-Type-Options: nosniff');
header('X-Frame-Options: SAMEORIGIN');
header('Referrer-Policy: strict-origin-when-cross-origin');

$root = dirname(__DIR__);

require $root . '/src/Core/App.php';
Sklad\Core\App::registerAutoload($root);

$app = new Sklad\Core\App($root);

// Политика ставится после сборки приложения: разовый ключ для встроенных
// блоков берётся у него же, и он обязан совпасть в заголовке и в
// разметке — иначе не выполнится ни счётчик, ни карточка организации.
header('Content-Security-Policy: ' . $app->securityPolicy());

require $root . '/src/routes.php';

$app->run();
